    static func suggestions(for word: String) -> [String] {
        let w = word.lowercased().trimmingCharacters(in: .punctuationCharacters)
        return keywords[w] ?? []
    }

    static func search(_ q: String) -> [String] {
        let s = q.lowercased()
        guard !s.isEmpty else { return [] }
        var out: [String] = []
        for (k, v) in keywords where k.hasPrefix(s) { for e in v where !out.contains(e) { out.append(e) } }
        return out
    }
